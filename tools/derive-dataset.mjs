#!/usr/bin/env node
/* Derives a sanitized dataset module from a real VIP extract, for the
   prototype to evaluate audiences against REAL distributions.

     node tools/derive-dataset.mjs <VIP.LOAN> <VIP.NAME>

   Writes src/symitarDataset.js. Sanitization: accounts re-keyed to
   sequential IDs; only loan facts (type code, balance, payment, rate,
   date offsets) and per-account aggregate flags (joint names, has email/
   mobile) are kept. No names, SSNs, addresses, phones, or raw account
   numbers leave the source files. */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const [loanPath, namePath] = process.argv.slice(2)
if (!loanPath || !namePath) {
  console.error('usage: node tools/derive-dataset.mjs <VIP.LOAN> <VIP.NAME>')
  process.exit(1)
}

const SENT = '--/--/----'
const parse = (f) => {
  const lines = fs.readFileSync(f, 'utf8').split(/\r?\n/).filter((l) => l.length)
  return { header: lines[0].split('|'), rows: lines.slice(1).map((l) => l.split('|')) }
}
const col = (p, h) => p.header.findIndex((x) => x.toLowerCase() === h.toLowerCase())
const num = (v) => {
  const n = Number((v ?? '').replace(/[,%$]/g, ''))
  return isNaN(n) ? null : n
}
const dateOffsetDays = (v, ref) => {
  const t = (v ?? '').trim()
  if (!t || t === SENT) return null
  const d = new Date(t)
  if (isNaN(d)) return null
  return Math.round((d - ref) / 86400000)
}

const m = path.basename(loanPath).match(/(\d{2})(\d{2})(\d{2})/)
const fileDate = m ? `20${m[3]}-${m[1]}-${m[2]}` : new Date().toISOString().slice(0, 10)
const ref = new Date(fileDate)

const loan = parse(loanPath)
const name = parse(namePath)

const L = {
  acct: col(loan, 'Account Number'), id: col(loan, 'Loan ID'), type: col(loan, 'Loan Type'),
  bal: col(loan, 'Loan Balance'), pay: col(loan, 'Payment'), due: col(loan, 'Due Date'),
  rate: col(loan, 'Interest Rate'), mat: col(loan, 'Maturity Date'), open: col(loan, 'Open Date'),
}
const N = {
  acct: col(name, 'Account Number'), type: col(name, 'Name Type'),
  email: col(name, 'E-Mail Address'), mobile: col(name, 'Mobile Phone'),
}

// account universe from NAME (includes loan-less members)
const accounts = new Map()
for (const r of name.rows) {
  const key = r[N.acct]
  if (!accounts.has(key)) accounts.set(key, { names: 0, joint: 0, hasEmail: false, hasMobile: false, loans: [] })
  const a = accounts.get(key)
  a.names++
  if (r[N.type] !== '00') a.joint++
  if ((r[N.email] ?? '').trim()) a.hasEmail = true
  if ((r[N.mobile] ?? '').trim()) a.hasMobile = true
}
for (const r of loan.rows) {
  const key = r[L.acct]
  if (!accounts.has(key)) accounts.set(key, { names: 0, joint: 0, hasEmail: false, hasMobile: false, loans: [] })
  accounts.get(key).loans.push({
    code: r[L.type],
    balance: num(r[L.bal]),
    payment: num(r[L.pay]),
    rate: num(r[L.rate]),
    dueInDays: dateOffsetDays(r[L.due], ref),
    maturityInDays: dateOffsetDays(r[L.mat], ref),
    openYear: (() => { const d = dateOffsetDays(r[L.open], ref); return d === null ? null : new Date(ref.getTime() + d * 86400000).getFullYear() })(),
  })
}

// stable order, sequential ids
const keys = [...accounts.keys()].sort()
const out = keys.map((k, i) => ({ id: `M${String(i + 1).padStart(3, '0')}`, ...accounts.get(k) }))

const allLoans = out.flatMap((a) => a.loans)
const typeCounts = {}
for (const l of allLoans) typeCounts[l.code] = (typeCounts[l.code] ?? 0) + 1
const stats = {
  fileDate,
  accounts: out.length,
  loanAccounts: out.filter((a) => a.loans.length).length,
  loans: allLoans.length,
  multiLoanAccounts: out.filter((a) => a.loans.length >= 2).length,
  maxLoans: Math.max(...out.map((a) => a.loans.length)),
  typeCounts,
  duePast: allLoans.filter((l) => l.dueInDays !== null && l.dueInDays < 0).length,
  dueFuture: allLoans.filter((l) => l.dueInDays !== null && l.dueInDays >= 0).length,
  dueUnset: allLoans.filter((l) => l.dueInDays === null).length,
  maturityUnset: allLoans.filter((l) => l.maturityInDays === null).length,
  emailPct: Math.round((100 * out.filter((a) => a.hasEmail).length) / out.length),
  mobilePct: Math.round((100 * out.filter((a) => a.hasMobile).length) / out.length),
  jointAccounts: out.filter((a) => a.joint > 0).length,
  loanCols: loan.header.length,
  nameCols: name.header.length,
}

const dest = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'symitarDataset.js')
fs.writeFileSync(
  dest,
  `/* Generated by tools/derive-dataset.mjs from a real VIP extract.
   Sanitized: sequential account IDs, loan facts and aggregate flags only —
   no names, SSNs, contact data, or raw account numbers. Do not edit. */
export const SYMITAR_STATS = ${JSON.stringify(stats, null, 2)}

export const SYMITAR_ACCOUNTS = ${JSON.stringify(out)}
`
)
console.log(`wrote ${dest}: ${out.length} accounts · ${allLoans.length} loans · file date ${fileDate}`)
console.log('stats:', JSON.stringify(stats))
